function emojiGet(mark) { return EMOJI_MAP[mark] || mark; }

function emojiReplace(text) {
    let result = text;
    for (const [mark, emoji] of Object.entries(EMOJI_MAP)) {
        result = result.split(mark).join(emoji);
    }
    return result;
}

