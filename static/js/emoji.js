function getCustomEmojis() {
    try { return JSON.parse(localStorage.getItem("custom_emojis") || "[]"); }
    catch(e) { return []; }
}
function saveCustomEmojis(list) {
    localStorage.setItem("custom_emojis", JSON.stringify(list));
}

function buildEmojiList() {
    var custom = getCustomEmojis();
    var list = [];
    // custom emojis first
    custom.forEach(function(item) {
        list.push({ mark: item.mark, emoji: item.emoji, custom: true });
    });
    // then defaults
    DEFAULT_EMOJI_LIST.forEach(function(mark) {
        var emoji = EMOJI_MAP[mark];
        if (emoji) list.push({ mark: mark, emoji: emoji, custom: false });
    });
    return list;
}
